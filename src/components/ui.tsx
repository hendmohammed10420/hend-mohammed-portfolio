import { motion, type HTMLMotionProps } from 'framer-motion'
import type { ReactNode } from 'react'

/** Fades + slides children in when scrolled into view */
export function Reveal({ children, delay = 0, ...rest }: { children: ReactNode; delay?: number } & HTMLMotionProps<'div'>) {
  return (
    <motion.div
      initial={{ opacity: 0, y: 28 }}
      whileInView={{ opacity: 1, y: 0 }}
      viewport={{ once: true, margin: '-60px' }}
      transition={{ duration: 0.6, delay, ease: [0.22, 1, 0.36, 1] }}
      {...rest}
    >
      {children}
    </motion.div>
  )
}

export function SectionHeader({ kicker, title, sub }: { kicker: string; title: string; sub?: string }) {
  return (
    <Reveal className="mb-12 max-w-2xl">
      <p className="mb-3 font-mono text-sm tracking-wider text-cyan-300/80">
        <span className="text-violet-400">//</span> {kicker}
      </p>
      <h2 className="text-3xl font-bold leading-tight text-white md:text-4xl">{title}</h2>
      {sub && <p className="mt-3 text-gray-400">{sub}</p>}
    </Reveal>
  )
}

